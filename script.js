function translatePage(language) {
  const dictionary = translations[language];
  const pageTitles = {
    ar: {
      "index.html": "Luma Supply | إضاءة أفضل",
      "categories.html": "الفئات | Luma Supply",
      "products.html": "المنتجات | Luma Supply",
      "product.html": "تفاصيل المنتج | Luma Supply",
      "about.html": "عن المتجر | Luma Supply",
      "contact.html": "استفسار عن منتج | Luma Supply"
    },
    en: {
      "index.html": "Luma Supply | Better light",
      "categories.html": "Categories | Luma Supply",
      "products.html": "Products | Luma Supply",
      "product.html": "Product details | Luma Supply",
      "about.html": "About | Luma Supply",
      "contact.html": "Product enquiry | Luma Supply"
    }
  };
  const currentPage = location.pathname.split("/").pop() || "index.html";
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = pageTitles[language][currentPage] || pageTitles[language]["index.html"];
  const descriptionMeta = document.querySelector('meta[name="description"]');
  if (descriptionMeta) descriptionMeta.content = dictionary.metaDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(",").forEach((mapping) => {
      const [attribute, key] = mapping.trim().split(":");
      if (dictionary[key] !== undefined) element.setAttribute(attribute, dictionary[key]);
    });
  });

  document.querySelectorAll(".language-toggle").forEach((button) => {
    const currentLabel = button.querySelector(".language-current");
    const nextLabel = button.querySelector(".language-next");
    if (currentLabel) currentLabel.textContent = language === "ar" ? "عربي" : "EN";
    if (nextLabel) nextLabel.textContent = language === "ar" ? "EN" : "عربي";
    button.setAttribute("aria-pressed", String(language === "en"));
  });

  const menuToggle = document.querySelector(".menu-toggle");
  if (menuToggle) {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute(
      "aria-label",
      dictionary[isExpanded ? "menuCloseLabel" : "menuLabel"]
    );
  }

  document.querySelectorAll(".category-item").forEach((item) => {
    const name = item.querySelector(".category-name [data-i18n]");
    if (name) item.setAttribute("aria-label", dictionary[name.dataset.i18n]);
  });
}

function getLanguage() {
  try {
    const saved = localStorage.getItem("luma-language");
    return saved === "en" ? "en" : "ar";
  } catch {
    return "ar";
  }
}

let currentLanguage = getLanguage();
translatePage(currentLanguage);

let isLanguageSwitching = false;

document.querySelectorAll(".language-toggle").forEach((button) => {
  button.addEventListener("click", () => {
    if (isLanguageSwitching) return;

    const nextLanguage = currentLanguage === "ar" ? "en" : "ar";
    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const animatedElements = reduceMotion
      ? []
      : [...document.querySelectorAll("[data-i18n], .language-toggle")].filter((element) => {
          if (element.parentElement?.closest("[data-i18n]")) return false;
          const bounds = element.getBoundingClientRect();
          return bounds.bottom > 0
            && bounds.top < window.innerHeight
            && bounds.right > 0
            && bounds.left < window.innerWidth;
        });

    currentLanguage = nextLanguage;
    try {
      localStorage.setItem("luma-language", currentLanguage);
    } catch {
      // The language switch still works when storage is unavailable.
    }
    translatePage(currentLanguage);

    if (animatedElements.length) {
      isLanguageSwitching = true;
      animatedElements.forEach((element) => element.classList.add("language-copy-enter"));
      window.setTimeout(() => {
        animatedElements.forEach((element) => element.classList.remove("language-copy-enter"));
        isLanguageSwitching = false;
      }, 420);
    }
  });
});

const menuButton = document.querySelector(".menu-toggle");
const mobileNav = document.querySelector(".mobile-nav");

menuButton?.addEventListener("click", () => {
  const isExpanded = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!isExpanded));
  mobileNav.hidden = isExpanded;
  menuButton.setAttribute(
    "aria-label",
    translations[currentLanguage][isExpanded ? "menuLabel" : "menuCloseLabel"]
  );
});

mobileNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    mobileNav.hidden = true;
    menuButton?.setAttribute("aria-expanded", "false");
    menuButton?.setAttribute("aria-label", translations[currentLanguage].menuLabel);
  });
});

const pageName = location.pathname.split("/").pop();
const query = new URLSearchParams(location.search);
const itemId = query.get("item");
const selectedProduct = productData[itemId];

if (pageName === "product.html" && selectedProduct) {
  const title = document.querySelector("#detail-title");
  const description = document.querySelector("#detail-description");
  const check = document.querySelector("#detail-check");
  const image = document.querySelector("#detail-image");
  title.dataset.i18n = selectedProduct.title;
  description.dataset.i18n = selectedProduct.description;
  check.dataset.i18n = selectedProduct.check;
  image.dataset.i18nAttr = `alt:${selectedProduct.alt}`;
  image.src = `https://images.unsplash.com/${selectedProduct.image}?auto=format&fit=crop&w=1200&q=85`;
  document.querySelector("#detail-contact").href = `contact.html?item=${encodeURIComponent(itemId)}`;
  translatePage(currentLanguage);
}

if (pageName === "contact.html") {
  const contactProduct = document.querySelector("#contact-product");
  if (selectedProduct && contactProduct) {
    contactProduct.dataset.i18n = selectedProduct.title;
    translatePage(currentLanguage);
  }
}

if (pageName === "products.html") {
  const selectedCategory = query.get("category");
  if (selectedCategory) {
    const matchingProduct = categoryProduct[selectedCategory];
    let hasMatches = false;
    document.querySelectorAll(".simple-product-list article").forEach((article) => {
      article.hidden = article.dataset.category !== matchingProduct;
      hasMatches ||= !article.hidden;
    });
    document.querySelector("#category-empty").hidden = hasMatches;
  }
}

const year = document.querySelector("#year");
if (year) year.textContent = String(new Date().getFullYear());
